"""Embed reviewed USB assets for browser-local ZIP generation (no fetch/CDN)."""
from pathlib import Path
import base64
import hashlib
import json

root = Path(__file__).resolve().parents[1]
source = root / 'docs/usb'
assets = {}
for path in sorted(source.rglob('*')):
    if path.is_file():
        data = path.read_bytes()
        assets[path.relative_to(source).as_posix()] = {
            'base64': base64.b64encode(data).decode('ascii'),
            'bytes': len(data),
            'sha256': hashlib.sha256(data).hexdigest(),
        }
assert set(assets) == {'mp3/a.mp3', 'mp3/b.mp3', 'mp3/c.mp3', 'mp3/d.mp3',
                       'js/run.js', 'css/init.css', 'dev.html', 'mp3title.txt', 'tweaks.sh', 'restore.sh', 'mzd/start.sh',
                       'mzd/installer.sh', 'mzd/common.sh', 'mzd/save-original.sh', 'mzd/originals.md5',
                       'mzd/patches/list-beep.sh', 'mzd/patches/list-beep.sed',
                       'mzd/patches/shorter-delay.sh', 'mzd/patches/shorter-delay.sed',
                       'mzd/patches/main-menu-loop.sh', 'mzd/patches/main-menu-loop.sed',
                       'mzd/patches/list-loop.sh', 'mzd/patches/list-loop.awk',
                       'mzd/dispatch.sh', 'mzd/file-job.sh', 'mzd/ssh-job.sh', 'mzd/patches/ssh-bringback.sh',
                       'mzd/ssh/service.sh', 'mzd/ssh/sshd_config', 'mzd/ssh/password.hash', 'mzd/ssh-log-marker.txt'}
reference = json.loads((root / 'docs/mp3-reference.json').read_text('utf-8'))
for name, expected in reference['files'].items():
    assert name in assets, f'Missing original MP3 entry dependency: {name}'
    assert assets[name]['bytes'] == expected['bytes'] and assets[name]['sha256'] == expected['sha256'], f'Modified original MP3 entry file: {name}'
(root / 'docs/usb-assets.js').write_text(
    '// Generated by web-tools/build-usb-assets.py; do not edit.\n'
    + 'globalThis.MZD_MP3_REFERENCE = ' + json.dumps(reference, indent=2) + ';\n'
    + 'globalThis.MZD_USB_ASSETS = ' + json.dumps(assets, indent=2) + ';\n',
    encoding='utf-8', newline='\n')
print(f'Embedded {len(assets)} USB assets ({sum(a["bytes"] for a in assets.values())} bytes).')
